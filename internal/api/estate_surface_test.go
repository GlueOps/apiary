// servedSpec fetches the OpenAPI document the running process actually serves.
//
// huma registers OpenAPIPath+".json" itself (v2.39.1 api.go:563), so this goes
// through the real chi router rather than reading a.API.OpenAPI() directly. The
// distinction matters: a document that exists in memory but is not reachable at
// the URL the SDK generator and the docs page point at is not a served spec.
func servedSpec(t *testing.T, a *App) map[string]any {
	t.Helper()

	req := httptest.NewRequest(http.MethodGet, a.BasePath+"/openapi.json", nil)
	rec := httptest.NewRecorder()
	a.Router.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		t.Fatalf("GET %s/openapi.json answered %d — the spec the SDK is generated from is not being served",
			a.BasePath, rec.Code)
	}

	var doc map[string]any
	if err := json.Unmarshal(rec.Body.Bytes(), &doc); err != nil {
		t.Fatalf("served spec is not JSON: %v", err)
	}
	return doc
}

// specTriples reduces an OpenAPI document to the identity of each operation.
//
// Identity only — never the whole document. docs/openapi.json is generated by
// `go run . generate sdk`, which pins the bind address so the artifact does not
// depend on whoever ran it; the test server binds wherever the test config says.
// The two therefore differ in their servers block and $schema examples and would
// never byte-match. What must match is which operations exist.
func specTriples(t *testing.T, doc map[string]any) map[string]bool {
	t.Helper()

	paths, ok := doc["paths"].(map[string]any)
	if !ok {
		t.Fatal("spec has no paths object")
	}

	out := map[string]bool{}
	for path, raw := range paths {
		item, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		for method, rawOp := range item {
			op, ok := rawOp.(map[string]any)
			if !ok {
				continue
			}
			id, _ := op["operationId"].(string)
			if id == "" {
				continue
			}
			out[strings.ToUpper(method)+" "+path+" "+id] = true
		}
	}
	return out
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// isEstatePath reports whether a path has "estates" as a whole segment.
//
// A segment test rather than strings.Contains: a future /real-estates or
// /estates-archive must not be silently swept into — or out of — this group by
// substring luck.
func isEstatePath(path string) bool {
	for _, seg := range strings.Split(path, "/") {
		if seg == "estates" {
			return true
		}
	}
	return false
}

// TestEveryEstateOperationIsSecuredAndProtected derives the estate group from
// the spec instead of listing the five operations by hand, so a sixth is covered
// the day it is registered.
//
// This closes a hole the two existing generic tests share. Both branch on the
// operation's own Security declaration: TestSecuredOperationsRejectAnonymousCallers
// SKIPS an operation that declares none, and TestPublicOperationsDoNotRequireAuth
// only fails on a 401. So an estate operation that declares no security AND is
// registered on the public group passes both of them simultaneously, while
// serving another tenant's cloud credentials to anyone who asks. Selecting by
// PATH is what makes that combination detectable.
func TestEveryEstateOperationIsSecuredAndProtected(t *testing.T) {
	a := testApp(t)

	found := 0
	for _, op := range operations(t, a) {
		if !isEstatePath(op.Path) {
			continue
		}
		found++

		t.Run(op.ID, func(t *testing.T) {
			if !op.Secured {
				t.Fatalf("%s %s (%s) does not declare BearerAuth: the generated SDK will not send a "+
					"token and the docs page will not offer one, whatever the router happens to enforce",
					op.Method, op.Path, op.ID)
			}

			req := httptest.NewRequest(op.Method, concreteURL(op.Path), nil)
			rec := httptest.NewRecorder()
			a.Router.ServeHTTP(rec, req)

			// The declaration is not the enforcement. This is the half that
			// catches an estate operation registered on the public group.
			if rec.Code != http.StatusUnauthorized {
				t.Fatalf("%s %s (%s) answered an anonymous caller with %d, not 401 — it is registered "+
					"on the public group and every tenant's estates are readable without a token: %s",
					op.Method, op.Path, op.ID, rec.Code, rec.Body.String())
			}
		})
	}

	// Without this the whole group vanishing — estate.RegisterUserProtected
	// dropped from handlers.RegisterUserProtected — would be a vacuous pass over
	// an empty loop rather than a failure.
	if found == 0 {
		t.Fatal("no operation is registered under an /estates path: the estate handlers are not wired in at all")
	}
	t.Logf("%d estate operations are declared secure and refuse anonymous callers", found)
}

// TestServedSpecMatchesTheSpecTheSDKIsGeneratedFrom pins the served document
// against docs/openapi.json, which cmd/generate.go writes and
// openapi-ts.config.ts consumes as its `input`.
//
// Drift here is invisible at runtime and total for a client: an operation
// registered in Go but absent from docs/ never reaches the TypeScript SDK, and
// an operation deleted in Go but left in docs/ produces a client function that
// 404s. Neither shows up in a build or a lint.
func TestServedSpecMatchesTheSpecTheSDKIsGeneratedFrom(t *testing.T) {
	a := testApp(t)

	raw, err := os.ReadFile("../../docs/openapi.json")
	if err != nil {
		t.Fatalf("read docs/openapi.json: %v — this file is the SDK generator's input", err)
	}
	var onDisk map[string]any
	if err := json.Unmarshal(raw, &onDisk); err != nil {
		t.Fatalf("docs/openapi.json is not JSON: %v", err)
	}

	served := specTriples(t, servedSpec(t, a))
	generated := specTriples(t, onDisk)

	if len(served) == 0 {
		t.Fatal("the served spec declares no operations at all")
	}

	for _, op := range sortedKeys(served) {
		if !generated[op] {
			t.Errorf("%s is served but is NOT in docs/openapi.json: the generated TypeScript SDK has no "+
				"function for it. Re-run `go run . generate sdk`.", op)
		}
	}
	for _, op := range sortedKeys(generated) {
		if !served[op] {
			t.Errorf("%s is in docs/openapi.json but is NOT served: the generated TypeScript SDK exposes a "+
				"function that will 404. Re-run `go run . generate sdk`.", op)
		}
	}
}

// sdkFunctionName derives the @hey-api function name from an operationId the
// same way the generator does: kebab-case to camelCase.
//
//	estates-rotate-credential -> estatesRotateCredential
func sdkFunctionName(operationID string) string {
	parts := strings.Split(operationID, "-")
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		if i == 0 {
			r[0] = unicode.ToLower(r[0])
		} else {
			r[0] = unicode.ToUpper(r[0])
		}
		b.WriteString(string(r))
	}
	return b.String()
}

// TestEveryOperationHasAGeneratedTypeScriptSDKFunction is a staleness detector
// for the checked-in client, not a test of Go behaviour.
//
// It is derived from the served spec rather than a hand-written list, so a sixth
// estate operation is covered the day it is registered: rename or add an
// OperationID without re-running `go run . generate sdk` and sdk.gen.ts has no
// matching export, which is the point at which the UI silently loses the call.
func TestEveryOperationHasAGeneratedTypeScriptSDKFunction(t *testing.T) {
	a := testApp(t)

	sdk, err := os.ReadFile("../../ui/src/sdk/sdk.gen.ts")
	if err != nil {
		t.Fatalf("read ui/src/sdk/sdk.gen.ts: %v", err)
	}
	src := string(sdk)

	ops := specTriples(t, servedSpec(t, a))
	if len(ops) == 0 {
		t.Fatal("the served spec declares no operations at all")
	}

	estates := 0
	for _, triple := range sortedKeys(ops) {
		fields := strings.Fields(triple)
		id := fields[len(fields)-1]
		if isEstatePath(fields[1]) {
			estates++
		}

		// The trailing space is deliberate: "export const estatesGet " must not
		// be satisfied by "export const estatesGetOptions" from the react-query
		// plugin, which is a different symbol with a different signature.
		if !strings.Contains(src, "export const "+sdkFunctionName(id)+" ") {
			t.Errorf("operation %q has no `export const %s` in ui/src/sdk/sdk.gen.ts: the checked-in client "+
				"is stale. Re-run `go run . generate sdk`.", id, sdkFunctionName(id))
		}
	}

	if estates == 0 {
		t.Fatal("no estate operation reached the SDK check: the estate handlers are not registered")
	}
}
